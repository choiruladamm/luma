#!/usr/bin/env python3
"""Check that docs keep their structure and that code comments follow the policy.

Config: `hygiene.toml` at the repo root (template ships with the docs-hygiene skill).
Needs Python 3.11+ (tomllib).

Docs (`docs_dir/**/*.md`):
- front matter with `type`, `purpose`, `sections`; `##` headings equal `sections`;
- headings carry no issue numbers, dates, or history words;
- at most `max_doc_lines` lines; linked from the index;
- relative links and `#anchors` resolve; every image under the docs dir is used.

Comments (files under `code_dirs`; comment syntax by extension; strings are skipped):
- no words from the foreign-word list (quoted text and `allowed_terms` excepted);
- no history phrasing; no issue numbers outside TODO(#N), (#N), or evidence;
- `docs/<file>.md, <Section>` citations name an existing file and heading.

Usage:
  hygiene_check.py [--root DIR] [--config FILE] [--docs] [--comments [PATH ...]] [--staged] [--report]
  hygiene_check.py --hook   # Claude Code PostToolUse: checks the edited file, exit 2 on findings
  hygiene_check.py --version
No --docs/--comments: both. --staged checks the staged content (git index) of code files in
code_dirs/extra_files; any staged doc runs the full docs check, read from the working tree, so a
partly staged doc is judged by its unstaged text (CI checks the commit itself).
HYGIENE_MODE=report (or --report) prints findings and exits 0.
"""

import sys

# Bumped on every behavior change; the skill's check mode compares a repo's copy against it.
VERSION = "2026.11.19"

if sys.version_info < (3, 11):
    sys.exit("hygiene_check.py needs Python 3.11+ (tomllib).")

import fnmatch
import json
import os
import pathlib
import re
import subprocess
import tomllib
from typing import Callable, Iterator

DEFAULTS = {
    "docs_dir": "docs",
    "index": "docs/README.md",
    "max_doc_lines": 400,
    "code_dirs": ["."],
    "extra_files": [],
    "skip": [],
    "frozen": [],
    "allowed_terms": [],
    "foreign_words_file": "",
    "evidence_paths": [],
    "prose_files": ["README.md", "AGENTS.md", "CLAUDE.md", ".claude/rules", ".claude/skills"],
}
ALWAYS_SKIP = [
    ".claude/worktrees/*", "**/node_modules/**", "**/.git/**", "**/vendor/**", "**/dist/**", "**/build/**",
    "**/target/**", "**/.dart_tool/**", "**/.venv/**", "**/__pycache__/**",
    "*.g.dart", "*.freezed.dart", "*.mocks.dart", "app_localizations*.dart",
    "*.pb.go", "*_pb2.py", "*.min.js",
]
# Comment family: (line comment, block open, block close, string quotes, has docstrings).
SLASH = ("//", "/*", "*/", ("'", '"', "`"), False)
HASH = ("#", None, None, ("'", '"'), True)
DASH = ("--", None, None, ("'", '"'), False)
FAMILIES = {
    **{e: SLASH for e in (".dart", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".go", ".rs",
                          ".java", ".kt", ".kts", ".swift", ".c", ".h", ".cc", ".cpp", ".hpp",
                          ".cs", ".scala", ".jsonc", ".css", ".scss")},
    **{e: HASH for e in (".py", ".rb", ".sh", ".bash", ".zsh", ".yaml", ".yml", ".toml", ".pl", ".r")},
    **{e: DASH for e in (".sql", ".lua", ".hs")},
}
NO_DOCSTRING = {".rb", ".sh", ".bash", ".zsh", ".yaml", ".yml", ".toml", ".pl", ".r", ".mk", ""}
TYPES = {"reference", "explanation", "how-to", "index"}

GENERATED = re.compile(
    r"@generated|do not edit|code generated .* do not edit|auto-?generated|generated by \S+", re.I
)
DIRECTIVE = re.compile(
    r"^(?:ignore(?:_for_file)?:|noqa|type:\s*ignore|pragma|eslint-|@ts-|prettier-ignore|"
    r"istanbul|c8 |go:|nolint|fmt:|pylint:|mypy:|coverage:|region|endregion|<reference|"
    r"shellcheck|rubocop:|biome-ignore|deno-lint)",
    re.IGNORECASE,
)
HISTORY = re.compile(r"\b(?:changed from|used to|previously|was added|added for|no longer used)\b", re.I)
ISSUE = re.compile(r"(?<![\w&/])#\d+\b")
ALLOWED_ISSUE = re.compile(r"TODO\(#\d+\)|\(#\d+\)|spike #\d+|eval #\d+|#\d+ (?:live )?evidence")
QUOTED = re.compile(r'"[^"]*"|“[^”]*”|`[^`]*`')
OPEN_QUOTE = re.compile(r'["“][^"”]*$')
CLOSE_QUOTE = re.compile(r'^[^"”]*["”]')
CITE = re.compile(r"(docs/[\w/.-]+\.md)(?:,\s*([^)\n]+))?")
LINK = re.compile(r"\]\(([^)\s]+?\.md)?(#[^)\s]*)?\)")
IMAGE = re.compile(r"[\w./-]*images/[\w.-]+\.(?:png|jpe?g|gif|svg|webp)")
BAD_HEADING = re.compile(
    r"#\d+|\b20\d\d\b|\b(?:history|historical|changelog|todo|deprecated|legacy|old)\b", re.I
)

errors: list[str] = []
Reader = Callable[[pathlib.Path], str]


def read_disk(path: pathlib.Path) -> str:
    return path.read_text(errors="ignore")


def load_config(root: pathlib.Path, path: pathlib.Path | None = None) -> dict:
    cfg = dict(DEFAULTS)
    path = path or root / "hygiene.toml"
    if path.exists():
        cfg.update(tomllib.loads(path.read_text()))
    return cfg


def skipped(rel: str, cfg: dict) -> bool:
    patterns = ALWAYS_SKIP + cfg["skip"] + cfg["frozen"]
    name = pathlib.PurePath(rel).name
    return any(fnmatch.fnmatch(rel, p) or fnmatch.fnmatch(name, p) for p in patterns)


# ---------- docs ----------

_heads: dict[pathlib.Path, list[str]] = {}


def heads(path: pathlib.Path) -> list[str]:
    if path not in _heads:
        out, fence = [], False
        for line in path.read_text().splitlines():
            if line.startswith("```"):
                fence = not fence
            elif not fence and line.startswith("#"):
                out.append(line.lstrip("#").strip())
        _heads[path] = out
    return _heads[path]


def slug(heading: str) -> str:
    s = re.sub(r"[`*_~]", "", heading.lower())
    s = re.sub(r"[^\w\- ]", "", s)
    return s.replace(" ", "-")


def front_matter(lines: list[str]) -> dict | None:
    if not lines or lines[0] != "---":
        return None
    try:
        end = lines.index("---", 1)
    except ValueError:
        return None
    meta = {}
    for line in lines[1:end]:
        key, _, value = line.partition(":")
        meta[key.strip()] = value.split(" #")[0].strip()
    return meta


def linked(index: pathlib.Path) -> set[pathlib.Path]:
    out = set()
    if index.exists():
        for m in LINK.finditer(index.read_text()):
            if m.group(1) and not m.group(1).startswith(("http://", "https://")):
                out.add((index.parent / m.group(1)).resolve())
    return out


def check_doc(root: pathlib.Path, doc: pathlib.Path, cfg: dict, index_links: set) -> None:
    name = str(doc.relative_to(root))
    lines = doc.read_text().splitlines()
    if len(lines) > cfg["max_doc_lines"]:
        errors.append(f"{name}: {len(lines)} lines, max {cfg['max_doc_lines']}; split it")
    fence, found = False, []
    for n, line in enumerate(lines, 1):
        if line.startswith("```"):
            fence = not fence
        if fence or not line.startswith("#"):
            continue
        if BAD_HEADING.search(line.lstrip("#")):
            errors.append(f"{name}:{n}: heading has an issue number, date, or history word")
        if line.startswith("## "):
            found.append(line[3:].strip())
    meta = front_matter(lines)
    if meta is None:
        errors.append(f"{name}: missing front matter (type, purpose, sections)")
    else:
        if meta.get("type") not in TYPES:
            errors.append(f"{name}: type must be one of {sorted(TYPES)}")
        if not meta.get("purpose"):
            errors.append(f"{name}: front matter needs a purpose")
        raw = meta.get("sections", "")
        if raw.startswith("[") and raw.endswith("]"):
            sections = [s.strip() for s in raw[1:-1].split(",") if s.strip()]
            if found != sections:
                errors.append(f"{name}: ## headings {found} don't match sections {sections}")
        else:
            errors.append(f"{name}: sections must be a [list]")
    if doc.resolve() != (root / cfg["index"]).resolve() and doc.resolve() not in index_links:
        errors.append(f"{name}: not linked from {cfg['index']}")


def check_links(root: pathlib.Path, doc: pathlib.Path) -> None:
    for n, line in enumerate(doc.read_text().splitlines(), 1):
        for m in LINK.finditer(line):
            target, anchor = m.group(1), m.group(2)
            if target and target.startswith(("http://", "https://")):
                continue
            path = (doc.parent / target).resolve() if target else doc
            if target and not path.exists():
                errors.append(f"{doc.relative_to(root)}:{n}: broken link {target}")
            elif anchor and path.suffix == ".md" and slug(anchor[1:]) not in {slug(h) for h in heads(path)}:
                errors.append(f"{doc.relative_to(root)}:{n}: no heading for {target or ''}{anchor}")


def check_docs(root: pathlib.Path, cfg: dict, only: list[pathlib.Path] | None = None) -> None:
    if not cfg["docs_dir"]:
        return  # docs checks turned off in hygiene.toml
    docs_dir = root / cfg["docs_dir"]
    if not docs_dir.is_dir():
        errors.append(f"{cfg['docs_dir']}/: missing (set docs_dir = \"\" in hygiene.toml to skip docs checks)")
        return
    index = root / cfg["index"]
    if not index.exists():
        errors.append(f"{cfg['index']}: missing docs index")
    index_links = linked(index)
    docs = sorted(docs_dir.rglob("*.md"))
    for doc in docs:
        if only and doc.resolve() not in only:
            continue
        check_doc(root, doc, cfg, index_links)
        check_links(root, doc)
    if only:
        return
    readme = root / "README.md"
    if readme.exists():
        check_links(root, readme)
    used = set()
    for f in docs + [readme] + prose_files(root, cfg):
        if f.exists():
            used.update(pathlib.PurePath(p).name for p in IMAGE.findall(f.read_text(errors="ignore")))
    for image in docs_dir.rglob("*"):
        if image.is_file() and image.parent.name == "images" and image.name not in used:
            errors.append(f"{image.relative_to(root)}: image not referenced anywhere")


# ---------- comments ----------

def comments(text: str, family: tuple, docstrings: bool) -> Iterator[tuple[int, str]]:
    """Yields (line, text) for each comment line, skipping string literals.

    A small lexer, not a parser: line and block comments, single, double, backtick,
    and triple-quoted strings with backslash escapes, and (hash family) triple-quoted
    strings that start a line, read as docstrings.
    """
    line_c, block_open, block_close, quotes, _ = family
    i, n, line = 0, len(text), 1
    at_line_start = True
    while i < n:
        c = text[i]
        if c == "\n":
            line += 1
            i += 1
            at_line_start = True
            continue
        if c in " \t":
            i += 1
            continue
        starts_line = at_line_start
        at_line_start = False
        if text.startswith(line_c, i):
            end = text.find("\n", i)
            end = n if end < 0 else end
            if not (line_c == "#" and line == 1 and text.startswith("#!", i)):
                yield line, text[i + len(line_c):end].lstrip("/!").strip()
            i = end
            continue
        if block_open and text.startswith(block_open, i):
            end = text.find(block_close, i + 2)
            end = n if end < 0 else end
            chunk = text[i + 2:end]
            for k, part in enumerate(chunk.split("\n")):
                body = part.strip().lstrip("*").strip()
                if body:
                    yield line + k, body
            line += chunk.count("\n")
            i = end + len(block_close)
            continue
        triple = next((q * 3 for q in quotes if text.startswith(q * 3, i)), None)
        if triple:
            end = text.find(triple, i + 3)
            end = n if end < 0 else end
            chunk = text[i + 3:end]
            if docstrings and starts_line:
                for k, part in enumerate(chunk.split("\n")):
                    if part.strip():
                        yield line + k, part.strip()
            line += chunk.count("\n")
            i = end + 3
            continue
        if c in quotes:
            j = i + 1
            raw = i > 0 and text[i - 1] in "rR"
            while j < n and text[j] != c:
                if text[j] == "\\" and not raw:
                    j += 1
                elif text[j] == "\n" and c != "`":
                    break  # unterminated single-line string: stop at end of line
                j += 1
            line += text.count("\n", i, min(j, n))
            i = j + 1
            continue
        i += 1


def load_words(root: pathlib.Path, cfg: dict) -> re.Pattern | None:
    if not cfg["foreign_words_file"]:
        return None
    path = pathlib.Path(cfg["foreign_words_file"])
    path = path if path.is_absolute() else root / path
    lines = [l.split("#", 1)[0] for l in path.read_text().splitlines()]
    words = [w for l in lines for w in l.split()]
    return re.compile(r"\b(?:" + "|".join(map(re.escape, words)) + r")\b", re.I) if words else None


def check_citation(root: pathlib.Path, where: str, doc_path: str, section: str | None) -> None:
    doc = root / doc_path
    if not doc.exists():
        errors.append(f"{where}: cites missing {doc_path}")
        return
    if section and not section.startswith(("docs/", "#")):
        name = re.split(r"\)|\. ", section)[0].strip().rstrip(".").lower()
        if name and not any(name in h.lower() for h in heads(doc)):
            errors.append(f"{where}: no section '{name}' in {doc_path}")


def family_of(path: pathlib.Path) -> tuple | None:
    if path.name in {"Makefile", "Dockerfile"} or path.suffix == ".mk":
        return HASH
    return FAMILIES.get(path.suffix.lower())


def check_file_comments(root, path: pathlib.Path, cfg: dict, words, terms, read: Reader) -> None:
    rel = path.relative_to(root).as_posix()
    family = family_of(path)
    if family is None or skipped(rel, cfg):
        return
    text = read(path)
    if GENERATED.search("\n".join(text.splitlines()[:5])):
        return
    docstrings = family[4] and path.suffix.lower() not in NO_DOCSTRING
    evidence = any(fnmatch.fnmatch(rel, p) for p in cfg["evidence_paths"])
    in_quote, last = False, -1
    for n, body in comments(text, family, docstrings):
        if n != last + 1:
            in_quote = False
        last = n
        if not body or DIRECTIVE.match(body):
            continue
        where = f"{rel}:{n}"
        for c in CITE.finditer(body):
            check_citation(root, where, c.group(1), c.group(2))
        t = CLOSE_QUOTE.sub("", body, count=1) if in_quote else body
        t = QUOTED.sub("", t)
        in_quote = bool(OPEN_QUOTE.search(t))
        t = OPEN_QUOTE.sub("", t)
        if terms:
            t = terms.sub("", t)
        if words and words.search(t):
            errors.append(f"{where}: comment isn't English: {body[:70]}")
        elif HISTORY.search(t):
            errors.append(f"{where}: comment narrates history (belongs in the commit)")
        elif not evidence and ISSUE.search(ALLOWED_ISSUE.sub("", t)):
            errors.append(f"{where}: issue number outside TODO(#N), (#N), or evidence")


def code_files(root: pathlib.Path, cfg: dict, paths: list[pathlib.Path] | None) -> list[pathlib.Path]:
    bases = paths if paths is not None else (
        [root / d for d in cfg["code_dirs"]] + [root / f for f in cfg["extra_files"]]
    )
    out = []
    for base in bases:
        if base.is_file():
            out.append(base)
        elif base.is_dir():
            out += [f for f in base.rglob("*") if f.is_file() and ".git" not in f.parts]
    return out


def prose_files(root: pathlib.Path, cfg: dict) -> list[pathlib.Path]:
    out = []
    for entry in cfg["prose_files"]:
        p = root / entry
        found = [p] if p.is_file() else list(p.rglob("*.md")) if p.is_dir() else []
        out += [f for f in found if not skipped(f.relative_to(root).as_posix(), cfg)]
    return out


def check_comments(root, cfg: dict, paths: list[pathlib.Path] | None = None, read: Reader = read_disk) -> None:
    words = load_words(root, cfg)
    terms = re.compile("|".join(map(re.escape, cfg["allowed_terms"]))) if cfg["allowed_terms"] else None
    for f in code_files(root, cfg, paths):
        check_file_comments(root, f, cfg, words, terms, read)
    if paths is None:
        for f in prose_files(root, cfg):
            for n, line in enumerate(f.read_text(errors="ignore").splitlines(), 1):
                for c in CITE.finditer(line):
                    if not (root / c.group(1)).exists():
                        errors.append(f"{f.relative_to(root)}:{n}: cites missing {c.group(1)}")


# ---------- entry ----------

def staged(root: pathlib.Path) -> list[pathlib.Path]:
    out = subprocess.run(["git", "diff", "--cached", "--name-only", "-z", "--diff-filter=ACMR"],
                         cwd=root, capture_output=True, text=True, check=True).stdout
    return [root / p for p in out.split("\0") if p]


def read_index(root: pathlib.Path) -> Reader:
    def read(path: pathlib.Path) -> str:
        rel = path.relative_to(root).as_posix()
        out = subprocess.run(["git", "show", f":{rel}"], cwd=root, capture_output=True)
        return out.stdout.decode(errors="ignore") if out.returncode == 0 else ""
    return read


def main() -> int:
    args = sys.argv[1:]
    if "-h" in args or "--help" in args:
        print(__doc__)
        return 0
    if "--version" in args:
        print(VERSION)
        return 0
    root, config = pathlib.Path.cwd(), None
    for flag in ("--root", "--config"):
        if flag in args:
            i = args.index(flag)
            value = pathlib.Path(args[i + 1]).resolve()
            del args[i:i + 2]
            if flag == "--root":
                root = value
            else:
                config = value
    root = root.resolve()
    report = "--report" in args or os.environ.get("HYGIENE_MODE") == "report"
    cfg = load_config(root, config)

    if args == ["--hook"]:
        edited = pathlib.Path(json.load(sys.stdin).get("tool_input", {}).get("file_path", "")).resolve()
        if not edited.exists() or root not in edited.parents:
            return 0
        docs_dir = (root / cfg["docs_dir"]).resolve() if cfg["docs_dir"] else None
        if edited.suffix == ".md" and docs_dir and docs_dir in edited.parents:
            check_docs(root, cfg, [edited])
        else:
            check_comments(root, cfg, [edited])
        if errors:
            print("hygiene (see .claude/rules/):\n" + "\n".join(errors), file=sys.stderr)
        return 2 if errors else 0

    want_docs = "--docs" in args or "--comments" not in args
    want_comments = "--comments" in args or "--docs" not in args
    paths = [root / a for a in args if not a.startswith("--")] or None
    if "--staged" in args:
        files = staged(root)
        docs = [f.resolve() for f in files if f.suffix == ".md"]
        # Only files under code_dirs / extra_files, like a full run; a staged Makefile or CI
        # file is out of scope.
        scope = [(root / d).resolve() for d in cfg["code_dirs"] + cfg["extra_files"]]
        code = [f for f in files if f.suffix != ".md"
                and any(f.resolve() == s or s in f.resolve().parents for s in scope)]
        # A staged doc can break links in docs that aren't staged, so any staged doc runs the
        # full docs check. Docs are read from the working tree (CI checks the commit itself);
        # code comments from the staged blobs.
        if want_docs and docs:
            check_docs(root, cfg)
        if want_comments and code:
            check_comments(root, cfg, code, read_index(root))
    else:
        if want_docs:
            check_docs(root, cfg)
        if want_comments:
            check_comments(root, cfg, paths)

    print("\n".join(errors) or "hygiene: ok")
    return 0 if report or not errors else 1


if __name__ == "__main__":
    sys.exit(main())
